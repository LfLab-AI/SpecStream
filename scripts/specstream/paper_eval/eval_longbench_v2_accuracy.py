#!/usr/bin/env python3

import os
os.environ["OMP_NUM_THREADS"] = "1"
os.environ["MKL_NUM_THREADS"] = "1"

import argparse
import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

import requests
from tqdm import tqdm


def load_jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [
            json.loads(line)
            for line in f
            if line.strip()
        ]


def normalize_label(value):
    s = str(value).strip().upper()

    patterns = [
        r"THE\s+CORRECT\s+ANSWER\s+IS\s*\(?([ABCD])\)?",
        r"ANSWER\s*(?:IS|:|：)?\s*\(?([ABCD])\)?",
        r"^\s*\(?([ABCD])\)?(?:[\.\s,:：]|$)",
    ]

    for pattern in patterns:
        m = re.search(
            pattern,
            s,
        )

        if m:
            return m.group(1)

    matches = re.findall(
        r"\b([ABCD])\b",
        s,
    )

    if len(matches) == 1:
        return matches[0]

    return ""


def get_server_limits(base_url):
    root = base_url.rstrip("/")

    if root.endswith("/v1"):
        root = root[:-3]

    r = requests.get(
        root + "/server_info",
        timeout=30,
    )

    if not r.ok:
        raise RuntimeError(
            f"server_info failed: "
            f"HTTP {r.status_code}: "
            f"{r.text[:2000]}"
        )

    info = r.json()

    max_req = info.get(
        "max_req_input_len"
    )

    context = None

    internal = info.get(
        "internal_states",
        [],
    )

    if internal:
        context = internal[0].get(
            "context_length"
        )

    return (
        max_req,
        context,
    )


def infer(
    base_url,
    prompt,
    max_new_tokens,
    timeout,
):
    payload = {
        "text": prompt,
        "sampling_params": {
            "temperature": 0,
            "top_p": 1.0,
            "max_new_tokens":
                max_new_tokens,
            "ignore_eos": False,
        },
        "stream": False,
    }

    r = requests.post(
        base_url.rstrip("/")
        + "/generate",
        json=payload,
        timeout=timeout,
    )

    if not r.ok:
        raise RuntimeError(
            f"HTTP {r.status_code}: "
            f"{r.text[:4000]}"
        )

    obj = r.json()

    text = obj.get(
        "text",
        "",
    )

    if isinstance(text, list):
        text = (
            text[0]
            if text
            else ""
        )

    text = str(text)

    return (
        text,
        normalize_label(text),
    )


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--dataset",
        required=True,
        help=(
            "Prepared LongBench-v2 JSONL "
            "generated by prepare_longbench_v2_32k.py"
        ),
    )

    parser.add_argument(
        "--base-url",
        default="http://127.0.0.1:30000",
    )

    parser.add_argument(
        "--workers",
        type=int,
        default=2,
    )

    parser.add_argument(
        "--max-new-tokens",
        type=int,
        default=128,
    )

    parser.add_argument(
        "--limit",
        type=int,
        default=0,
    )

    parser.add_argument(
        "--timeout",
        type=int,
        default=1800,
    )

    parser.add_argument(
        "--output",
        required=True,
    )

    args = parser.parse_args()

    (
        server_max_req,
        server_context,
    ) = get_server_limits(
        args.base_url
    )

    print(
        "server_max_req_input_len =",
        server_max_req,
    )

    print(
        "server_context_length =",
        server_context,
    )

    rows = load_jsonl(
        args.dataset
    )

    if args.limit:
        rows = rows[:args.limit]

    if not rows:
        raise RuntimeError(
            "Prepared dataset is empty."
        )

    max_prompt_tokens = max(
        int(x["prompt_tokens"])
        for x in rows
    )

    print(
        "samples =",
        len(rows),
    )

    print(
        "max_prepared_prompt_tokens =",
        max_prompt_tokens,
    )

    if (
        server_max_req is not None
        and max_prompt_tokens
        >= server_max_req
    ):
        raise RuntimeError(
            f"Prepared prompt length "
            f"{max_prompt_tokens} exceeds "
            f"server max_req_input_len "
            f"{server_max_req}."
        )

    if (
        server_context is not None
        and max_prompt_tokens
        + args.max_new_tokens
        >= server_context
    ):
        raise RuntimeError(
            "Prepared prompt + generation "
            "budget exceeds server context."
        )

    outputs = [
        None
    ] * len(rows)

    with ThreadPoolExecutor(
        max_workers=args.workers
    ) as executor:

        future_to_idx = {
            executor.submit(
                infer,
                args.base_url,
                row["eval_prompt"],
                args.max_new_tokens,
                args.timeout,
            ): idx
            for idx, row in enumerate(rows)
        }

        for future in tqdm(
            as_completed(future_to_idx),
            total=len(future_to_idx),
            desc="LongBench-v2 inference",
            unit="sample",
        ):
            idx = future_to_idx[
                future
            ]

            row = rows[idx]

            gold = normalize_label(
                row["answer"]
            )

            try:
                text, pred = (
                    future.result()
                )

                outputs[idx] = {
                    "source_index":
                        row["source_index"],

                    "id":
                        row.get(
                            "_id",
                            "",
                        ),

                    "domain":
                        row.get(
                            "domain",
                            "",
                        ),

                    "difficulty":
                        row.get(
                            "difficulty",
                            "",
                        ),

                    "length_category":
                        row.get(
                            "length",
                            "",
                        ),

                    "prompt_tokens":
                        row[
                            "prompt_tokens"
                        ],

                    "truncated":
                        row[
                            "truncated"
                        ],

                    "expected_stream_eligible":
                        row[
                            "expected_stream_eligible"
                        ],

                    "prompt_sha256":
                        row[
                            "prompt_sha256"
                        ],

                    "gold":
                        gold,

                    "pred":
                        pred,

                    "correct":
                        pred == gold,

                    "output":
                        text,

                    "error":
                        "",
                }

            except Exception as exc:

                outputs[idx] = {
                    "source_index":
                        row["source_index"],

                    "id":
                        row.get(
                            "_id",
                            "",
                        ),

                    "domain":
                        row.get(
                            "domain",
                            "",
                        ),

                    "difficulty":
                        row.get(
                            "difficulty",
                            "",
                        ),

                    "length_category":
                        row.get(
                            "length",
                            "",
                        ),

                    "prompt_tokens":
                        row[
                            "prompt_tokens"
                        ],

                    "truncated":
                        row[
                            "truncated"
                        ],

                    "expected_stream_eligible":
                        row[
                            "expected_stream_eligible"
                        ],

                    "prompt_sha256":
                        row[
                            "prompt_sha256"
                        ],

                    "gold":
                        gold,

                    "pred":
                        "",

                    "correct":
                        False,

                    "output":
                        "",

                    "error":
                        repr(exc),
                }

    output_path = Path(
        args.output
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with output_path.open(
        "w",
        encoding="utf-8",
    ) as f:

        for row in outputs:
            f.write(
                json.dumps(
                    row,
                    ensure_ascii=False,
                )
                + "\n"
            )

    total = len(outputs)

    success = [
        x
        for x in outputs
        if not x["error"]
    ]

    errors = (
        total
        - len(success)
    )

    accuracy = (
        sum(
            bool(x["correct"])
            for x in outputs
        )
        / total
    )

    stream_rows = [
        x
        for x in outputs
        if x[
            "expected_stream_eligible"
        ]
    ]

    stream_accuracy = (
        sum(
            bool(x["correct"])
            for x in stream_rows
        )
        / len(stream_rows)
        if stream_rows
        else 0.0
    )

    print()
    print("=" * 72)
    print("LongBench-v2 summary")
    print("=" * 72)

    print(
        f"total={total}"
    )

    print(
        f"success={len(success)}"
    )

    print(
        f"errors={errors}"
    )

    print(
        f"accuracy_all="
        f"{accuracy:.6f}"
    )

    print(
        "stream_eligible="
        f"{len(stream_rows)}"
    )

    print(
        "accuracy_stream_eligible="
        f"{stream_accuracy:.6f}"
    )

    print(
        "output=",
        output_path,
    )

    if errors:
        print()
        print(
            "ERROR: failed requests exist. "
            "Do not use this run in the paper."
        )

        sys.exit(2)


if __name__ == "__main__":
    main()
